const LANG_KEY = 'truck_sim_lang';

function detectLang() {
    const browser = (navigator.language || 'en').toLowerCase();
    for (const lang of SUPPORTED_LANGS) {
        if (browser.startsWith(lang)) return lang;
    }
    return 'en';
}

let currentLang;
try {
    const stored = localStorage.getItem(LANG_KEY);
    currentLang = SUPPORTED_LANGS.includes(stored) ? stored : detectLang();
} catch (_) {
    currentLang = detectLang();
}

const listeners = new Set();

export function getLang() {
    return currentLang;
}

export function setLang(lang) {
    if (!SUPPORTED_LANGS.includes(lang) || lang === currentLang) return;
    currentLang = lang;
    try { localStorage.setItem(LANG_KEY, lang); } catch (_) {}
    listeners.forEach(fn => fn(lang));
}

export function onLangChange(fn) {
    listeners.add(fn);
    return () => listeners.delete(fn);
}

// 取当前语言下的 UI 字符串，找不到回退到英语
export function t(key, vars) {
    const dict = STRINGS[currentLang] || STRINGS.en;
    let s = dict[key] ?? STRINGS.en[key] ?? key;
    if (vars) {
        for (const k in vars) {
            s = s.replace('{' + k + '}', vars[k]);
        }
    }
    return s;
}

// 取 {en, zh, ja, ...} 形式数据的当前语言值，缺失回退到英语
export function localize(obj) {
    if (obj == null) return '';
    if (typeof obj === 'string') return obj;
    return obj[currentLang] ?? obj.en ?? Object.values(obj)[0] ?? '';
}
